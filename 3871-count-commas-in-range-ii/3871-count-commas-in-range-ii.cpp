class Solution {
public:
    long long countCommas(long long n) {
        if(n<1000){
            return 0;
        }
        else if (n>=1000 && n<1000000){
            return n-999;
        }
        else if (n>=1000000 && n<1000000000){
            return (n - 999999) * 2
                 + (999999 - 999);
        }
        else if(n>=1000000000 && n<1000000000000){
            return (n - 999999999) * 3
                 + (999999999 - 999999) * 2
                 + (999999 - 999);
        }
        else if(n>=1000000000000 && n<1000000000000000){
             return (n - 999999999999) * 4
                 + (999999999999 - 999999999) * 3
                 + (999999999 - 999999) * 2
                 + (999999 - 999);
        }
     return (n - 999999999999999) * 5
                 + (999999999999999 - 999999999999) * 4
                 + (999999999999 - 999999999) * 3
                 + (999999999 - 999999) * 2
                 + (999999 - 999);
    }
};